export function lookupZwiftRoute(
  routeId: string | number | undefined,
): StaticZwiftRoute | undefined {
  if (routeId === undefined || routeId === null) return undefined;
  const id = typeof routeId === "number" ? routeId : Number(String(routeId).trim());
  if (!Number.isInteger(id) || id <= 0) return undefined;
  const entry = STATIC_ZWIFT_ROUTES[id];
  if (!entry) return undefined;
  const [name, worldSlug, distanceKm, elevationM] = entry;
  return {
    id,
    name,
    world: formatWorldSlug(worldSlug) ?? worldSlug,
    distanceKm,
    elevationM,
  };
}
